using System.ComponentModel;
using System.Drawing;
using System.Windows.Forms;

namespace GtkWinForms.Tests.System.Windows.Forms;

/// <summary>
/// Tests for the drop-down lifecycle surface added to <see cref="ToolStripDropDown" /> — the
/// <c>Show</c>/<c>Close</c> methods, the <c>Opening</c>/<c>Opened</c> events, and the
/// <c>AutoClose</c>/<c>DropShadowEnabled</c> settings. Because they live on the base, they reach the whole
/// drop-down family (<see cref="ContextMenuStrip" />, <see cref="ToolStripDropDownMenu" />).
/// </summary>
[Collection("NonParallelCollection")]
public class ToolStripDropDownMembersFunctionalTests
{
    static ToolStripDropDownMembersFunctionalTests()
    {
        using var _ = new Form();
    }

    [Fact]
    public void Settings_HaveWinFormsDefaults_AndRoundTrip()
    {
        using var dd = new ToolStripDropDown();

        Assert.True(dd.AutoClose);
        Assert.True(dd.DropShadowEnabled);
        Assert.False(dd.AllowTransparency);
        Assert.False(dd.IsAutoGenerated);

        dd.AutoClose = false;
        dd.DropShadowEnabled = false;
        dd.AllowTransparency = true;

        Assert.False(dd.AutoClose);
        Assert.False(dd.DropShadowEnabled);
        Assert.True(dd.AllowTransparency);
    }

    [Fact]
    public void Show_RaisesOpeningThenOpened_InOrder()
    {
        using var dd = new ToolStripDropDown();
        var sequence = new List<string>();
        dd.Opening += (_, _) => sequence.Add("opening");
        dd.Opened += (_, _) => sequence.Add("opened");

        dd.Show(10, 20);

        Assert.Equal(new[] { "opening", "opened" }, sequence);
    }

    [Fact]
    public void Show_WhenOpeningCancelled_DoesNotRaiseOpened()
    {
        using var dd = new ToolStripDropDown();
        var openedRaised = false;
        dd.Opening += (_, e) => e.Cancel = true;
        dd.Opened += (_, _) => openedRaised = true;

        dd.Show(new Point(5, 5));

        Assert.False(openedRaised);
    }

    [Fact]
    public void ShowOverloads_AllResolveAndRaiseOpened()
    {
        using var dd = new ToolStripDropDown();
        using var anchor = new Button();
        var openedCount = 0;
        dd.Opened += (_, _) => openedCount++;

        dd.Show(new Point(1, 1));
        dd.Show(1, 1);
        dd.Show(anchor, new Point(2, 2));
        dd.Show(anchor, 2, 2);
        dd.Show(new Point(3, 3), ToolStripDropDownDirection.Right);
        dd.Show(anchor, new Point(4, 4), ToolStripDropDownDirection.Left);

        Assert.Equal(6, openedCount);
    }

    [Fact]
    public void Close_Resolves_OnBaseAndDerivedDropDowns()
    {
        using var dd = new ToolStripDropDown();
        using var ctx = new ContextMenuStrip();

        // Both overloads resolve on the base and the derived family, and do not throw.
        dd.Close();
        dd.Close(ToolStripDropDownCloseReason.CloseCalled);
        ctx.AutoClose = false;
        ctx.Close();

        Assert.False(ctx.AutoClose);
    }
}
