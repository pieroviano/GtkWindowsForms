namespace System.Windows.Forms;

/// <summary>
/// Specifies how a
/// <see cref="T:System.Windows.Forms.TableLayoutPanel" />
/// will gain additional rows or columns after its existing cells are full.
/// </summary>
public enum TableLayoutPanelGrowStyle
{
    /// <summary>
    /// The fixed size
    /// </summary>
    FixedSize,
    /// <summary>
    /// The add rows
    /// </summary>
    AddRows,
    /// <summary>
    /// The add columns
    /// </summary>
    AddColumns
}