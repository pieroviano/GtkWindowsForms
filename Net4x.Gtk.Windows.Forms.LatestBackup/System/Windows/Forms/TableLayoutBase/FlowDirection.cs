namespace System.Windows.Forms;

/// <summary>
/// Defines constants that specify the direction in which consecutive user interface (UI) elements are placed in a linear layout container
/// </summary>
public enum FlowDirection
{
    /// <summary>
    /// The left to right
    /// </summary>
    LeftToRight,
    /// <summary>
    /// The top down
    /// </summary>
    TopDown,
    /// <summary>
    /// The right to left
    /// </summary>
    RightToLeft,
    /// <summary>
    /// The bottom up
    /// </summary>
    BottomUp
}