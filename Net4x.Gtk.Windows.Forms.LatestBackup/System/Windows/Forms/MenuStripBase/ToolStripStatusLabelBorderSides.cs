namespace System.Windows.Forms
{
    /// <summary>
    /// Specifies which sides of a
    /// <see cref="System.Windows.Forms.ToolStripStatusLabel" />
    /// have borders.
    /// </summary>
    public enum ToolStripStatusLabelBorderSides
    {
        /// <summary>
        /// All sides of the
        /// <see cref="System.Windows.Forms.ToolStripStatusLabel" /> have borders.
        /// </summary>
        All = 0xF,
        /// <summary>
        /// Only the bottom side of the
        /// <see cref="System.Windows.Forms.ToolStripStatusLabel" /> has borders.
        /// </summary>
        Bottom = 0x8,
        /// <summary>
        /// Only the left side of the
        /// <see cref="System.Windows.Forms.ToolStripStatusLabel" /> has borders.
        /// </summary>
        Left = 0x1,
        /// <summary>
        /// Only the right side of the
        /// <see cref="System.Windows.Forms.ToolStripStatusLabel" /> has borders.
        /// </summary>
        Right = 0x4,
        /// <summary>
        /// Only the top side of the
        /// <see cref="System.Windows.Forms.ToolStripStatusLabel" /> has borders.
        /// </summary>
        Top = 0x2,
        /// <summary>
        /// The
        /// <see cref="System.Windows.Forms.ToolStripStatusLabel" /> has no borders.
        /// </summary>
        None = 0x0
    }
}
