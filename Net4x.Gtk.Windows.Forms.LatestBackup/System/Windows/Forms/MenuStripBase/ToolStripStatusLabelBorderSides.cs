namespace System.Windows.Forms;

/// <summary>
/// Specifies which sides of a
/// <see cref="T:System.Windows.Forms.ToolStripStatusLabel" /> have borders.
/// </summary>
public enum ToolStripStatusLabelBorderSides
{
    /// <summary>
    /// All
    /// </summary>
    All = 0xF,
    /// <summary>
    /// The bottom
    /// </summary>
    Bottom = 0x8,
    /// <summary>
    /// The left
    /// </summary>
    Left = 0x1,
    /// <summary>
    /// The right
    /// </summary>
    Right = 0x4,
    /// <summary>
    /// The top
    /// </summary>
    Top = 0x2,
    /// <summary>
    /// The none
    /// </summary>
    None = 0x0
}