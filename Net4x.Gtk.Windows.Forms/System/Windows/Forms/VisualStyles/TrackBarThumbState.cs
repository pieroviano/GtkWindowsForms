namespace System.Windows.Forms.VisualStyles;

/// <summary>Specifies the visual state of a TrackBarThumb drawn with visual styles.</summary>
public enum TrackBarThumbState
{
    /// <summary>The Normal state.</summary>
    Normal = 1,

    /// <summary>The Hot state.</summary>
    Hot = 2,

    /// <summary>The Pressed state.</summary>
    Pressed = 3,

    /// <summary>The Disabled state.</summary>
    Disabled = 5,
}
