namespace System.Windows.Forms.VisualStyles;

/// <summary>Specifies the visual state of a CheckBox drawn with visual styles.</summary>
public enum CheckBoxState
{
    /// <summary>The UncheckedNormal state.</summary>
    UncheckedNormal = 1,

    /// <summary>The UncheckedHot state.</summary>
    UncheckedHot = 2,

    /// <summary>The UncheckedPressed state.</summary>
    UncheckedPressed = 3,

    /// <summary>The UncheckedDisabled state.</summary>
    UncheckedDisabled = 4,

    /// <summary>The CheckedNormal state.</summary>
    CheckedNormal = 5,

    /// <summary>The CheckedHot state.</summary>
    CheckedHot = 6,

    /// <summary>The CheckedPressed state.</summary>
    CheckedPressed = 7,

    /// <summary>The CheckedDisabled state.</summary>
    CheckedDisabled = 8,

    /// <summary>The MixedNormal state.</summary>
    MixedNormal = 9,

    /// <summary>The MixedHot state.</summary>
    MixedHot = 10,

    /// <summary>The MixedPressed state.</summary>
    MixedPressed = 11,

    /// <summary>The MixedDisabled state.</summary>
    MixedDisabled = 12,
}
