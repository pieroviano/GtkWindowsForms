    Close = 0,

    /// <summary>A Minimize button.</summary>
    Minimize = 1,

    /// <summary>A Maximize button.</summary>
    Maximize = 2,

    /// <summary>A Restore button.</summary>
    Restore = 3,

    /// <summary>A Help button.</summary>
    Help = 4,
}
