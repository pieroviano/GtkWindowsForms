namespace System.Windows.Forms;

/// <summary>
/// Specifies the initial position of a form.
/// </summary>
public enum FormStartPosition
{
    /// <summary>
    /// The windows default location
    /// </summary>
    WindowsDefaultLocation,
    /// <summary>
    /// The center screen
    /// </summary>
    CenterScreen,
    /// <summary>
    /// The manual
    /// </summary>
    Manual,
    /// <summary>
    /// The center parent
    /// </summary>
    CenterParent,
    /// <summary>
    /// The windows default bounds
    /// </summary>
    WindowsDefaultBounds
}