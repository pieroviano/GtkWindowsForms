namespace System.Windows.Forms;
/// <summary>
/// Specifies the border styles that can be applied to the cells of a
/// <see cref="T:System.Windows.Forms.DataGridView" /> control.
/// </summary>
/// <filterpriority>
/// 2
/// </filterpriority>
public enum DataGridViewAdvancedCellBorderStyle
{
    /// <summary>
    /// The not set
    /// </summary>
    NotSet = 0,
    /// <summary>
    /// The none
    /// </summary>
    None = 1,
    /// <summary>
    /// The single
    /// </summary>
    Single = 2,
    /// <summary>
    /// The inset
    /// </summary>
    Inset = 3,
    /// <summary>
    /// The inset double
    /// </summary>
    InsetDouble = 4,
    /// <summary>
    /// The outset
    /// </summary>
    Outset = 5,
    /// <summary>
    /// The outset double
    /// </summary>
    OutsetDouble = 6,
    /// <summary>
    /// The outset partial
    /// </summary>
    OutsetPartial = 7
}
