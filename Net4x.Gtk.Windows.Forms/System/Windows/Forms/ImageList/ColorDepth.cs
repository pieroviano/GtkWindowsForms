namespace System.Windows.Forms;

/// <summary>
/// Specifies the number of colors used to display an image in an
/// <see cref="T:System.Windows.Forms.ImageList" /> control.
/// </summary>
public enum ColorDepth
{
    /// <summary>
    /// The depth4 bit
    /// </summary>
    Depth4Bit = 4,
    /// <summary>
    /// The depth8 bit
    /// </summary>
    Depth8Bit = 8,
    /// <summary>
    /// The depth16 bit
    /// </summary>
    Depth16Bit = 16,
    /// <summary>
    /// The depth24 bit
    /// </summary>
    Depth24Bit = 24,
    /// <summary>
    /// The depth32 bit
    /// </summary>
    Depth32Bit = 32,
}
