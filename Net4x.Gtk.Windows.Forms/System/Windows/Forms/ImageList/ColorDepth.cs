namespace System.Windows.Forms
{
    /// <summary>
    /// Specifies the number of colors used to display an image in an
    /// <see cref="System.Windows.Forms.ImageList" /> control.
    /// </summary>
    /// <filterpriority>
    /// 2
    /// </filterpriority>
    public enum ColorDepth
    {
        /// <summary>
        /// A 4-bit image.
        /// </summary>
        Depth4Bit = 4,
        /// <summary>
        /// An 8-bit image.
        /// </summary>
        Depth8Bit = 8,
        /// <summary>
        /// A 16-bit image.
        /// </summary>
        Depth16Bit = 16,
        /// <summary>
        /// A 24-bit image.
        /// </summary>
        Depth24Bit = 24,
        /// <summary>
        /// A 32-bit image.
        /// </summary>
        Depth32Bit = 32,
    }
}
