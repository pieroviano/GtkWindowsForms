namespace System.Windows.Forms.VisualStyles;

/// <summary>Identifies a FillType used with visual styles.</summary>
public enum FillType
{
    /// <summary>The Solid value.</summary>
    Solid = 0,

    /// <summary>The VerticalGradient value.</summary>
    VerticalGradient = 1,

    /// <summary>The HorizontalGradient value.</summary>
    HorizontalGradient = 2,

    /// <summary>The RadialGradient value.</summary>
    RadialGradient = 3,

    /// <summary>The TileImage value.</summary>
    TileImage = 4,
}
