using System.ComponentModel;
using System.Drawing;

namespace System.Windows.Forms;

/// <summary>
/// Drop-down-specific surface shared by <see cref="ToolStripDropDown" /> and its descendants
/// (<see cref="ContextMenuStrip" />, <see cref="ToolStripDropDownMenu" />, <see cref="ToolStripOverflow" />).
/// Adds the <c>Show</c>/<c>Close</c> lifecycle, the <see cref="Opening" />/<see cref="Opened" /> events, and
/// the <see cref="AutoClose" />/<see cref="DropShadowEnabled" /> settings so ported code that pops a menu or
/// hooks its open lifecycle compiles and runs.
/// </summary>
public partial class ToolStripDropDown
{
    /// <summary>
    /// Occurs as the drop-down is about to open; set <see cref="CancelEventArgs.Cancel" /> to suppress it.
    /// </summary>
    public event CancelEventHandler? Opening;

    /// <summary>Occurs after the drop-down has opened.</summary>
    public event EventHandler? Opened;

    /// <summary>
    /// Gets or sets a value indicating whether the drop-down closes automatically when it loses focus or an
    /// item is clicked. Defaults to <see langword="true" />.
    /// </summary>
    public bool AutoClose { get; set; } = true;

    /// <summary>Gets or sets a value indicating whether a drop shadow is shown behind the drop-down.</summary>
    public bool DropShadowEnabled { get; set; } = true;

    /// <summary>Gets or sets a value indicating whether the drop-down supports transparency.</summary>
    public bool AllowTransparency { get; set; }

    /// <summary>
    /// Gets a value indicating whether the drop-down was generated automatically by its owning item rather
    /// than assigned explicitly. Always <see langword="false" /> for a hand-constructed drop-down.
    /// </summary>
    public bool IsAutoGenerated => false;

    /// <summary>Displays the drop-down at the given screen location.</summary>
    /// <param name="screenLocation">The screen coordinates at which to display the drop-down.</param>
    public void Show(Point screenLocation) => ShowCore();

    /// <summary>Displays the drop-down at the given screen coordinates.</summary>
    /// <param name="x">The horizontal screen coordinate.</param>
    /// <param name="y">The vertical screen coordinate.</param>
    public void Show(int x, int y) => ShowCore();

    /// <summary>Displays the drop-down relative to the given control.</summary>
    /// <param name="control">The control the drop-down is positioned against.</param>
    /// <param name="position">The position relative to <paramref name="control" />.</param>
    public void Show(Control control, Point position) => ShowCore(control?.Widget, position.X, position.Y);

    /// <summary>Displays the drop-down relative to the given control.</summary>
    /// <param name="control">The control the drop-down is positioned against.</param>
    /// <param name="x">The horizontal position relative to <paramref name="control" />.</param>
    /// <param name="y">The vertical position relative to <paramref name="control" />.</param>
    public void Show(Control control, int x, int y) => ShowCore(control?.Widget, x, y);

    /// <summary>Displays the drop-down at the given location, expanding in the given direction.</summary>
    /// <param name="position">The screen position at which to display the drop-down.</param>
    /// <param name="direction">The direction in which the drop-down expands.</param>
    public void Show(Point position, ToolStripDropDownDirection direction) => ShowCore();

    /// <summary>Displays the drop-down relative to a control, expanding in the given direction.</summary>
    /// <param name="control">The control the drop-down is positioned against.</param>
    /// <param name="position">The position relative to <paramref name="control" />.</param>
    /// <param name="direction">The direction in which the drop-down expands.</param>
    public void Show(Control control, Point position, ToolStripDropDownDirection direction) => ShowCore(control?.Widget, position.X, position.Y);

    /// <summary>Closes the drop-down.</summary>
    public void Close() => CloseCore();

    /// <summary>Closes the drop-down, recording the reason it closed.</summary>
    /// <param name="reason">The reason the drop-down is closing.</param>
    public void Close(ToolStripDropDownCloseReason reason) => CloseCore();

    /// <summary>Raises the <see cref="Opening" /> event.</summary>
    /// <param name="e">A <see cref="CancelEventArgs" /> that carries the cancel flag.</param>
    protected virtual void OnOpening(CancelEventArgs e) => Opening?.Invoke(this, e);

    /// <summary>Raises the <see cref="Opened" /> event.</summary>
    /// <param name="e">An <see cref="EventArgs" /> that contains the event data.</param>
    protected virtual void OnOpened(EventArgs e) => Opened?.Invoke(this, e);

    private void ShowCore(Gtk.Widget? relativeTo = null, int x = 0, int y = 0)
    {
        var opening = new CancelEventArgs();
        OnOpening(opening);
        if (opening.Cancel)
        {
            return;
        }

        try
        {
            // Gtk4: a popover must be parented (gtk_widget_set_parent) before Popup(), and points at a
            // rectangle in the parent's coordinate space. Anchor to the control the menu is shown against
            // (e.g. the right-clicked control) at the requested point; without a parent Popup() aborts, which
            // is why context menus never appeared.
            if (relativeTo != null)
            {
                if (self.Parent != relativeTo)
                {
                    if (self.Parent != null)
                    {
                        self.Unparent();
                    }

                    self.Parent = relativeTo;
                }

                self.Autohide = true;
                self.HasArrow = false;
                self.Position = Gtk.PositionType.Bottom;
                self.PointingTo = new Gdk.Rectangle(x, y, 1, 1);
            }

            // Popup() creates a GDK popup surface anchored to the parent's surface, so the parent must be
            // realized and on screen; on an unmapped parent GDK aborts (not a catchable managed exception).
            if (self.Parent != null && self.Parent.IsMapped)
            {
                self.Popup();
            }
        }
        catch (Exception ex)
        {
            global::System.Diagnostics.GtkLogger.Debug($"ToolStripDropDown.Show popup failed: {ex.Message}");
        }

        OnOpened(EventArgs.Empty);
    }

    private void CloseCore()
    {
        try
        {
            self.Popdown();
        }
        catch (Exception ex)
        {
            global::System.Diagnostics.GtkLogger.Debug($"ToolStripDropDown.Close failed: {ex.Message}");
        }
    }
}
